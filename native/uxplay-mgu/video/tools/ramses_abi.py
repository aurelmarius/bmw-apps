"""Symbol lists, link stubs and import checks for the unit's libramses:
19.0.14 on iDrive 7, 27.0.116r1 on iDrive 8.

    ramses_abi.py dump-symbols LIB > abi/libramses19.symbols   (or 27)
    ramses_abi.py stub-source abi/libramses19.symbols > stub.c
    ramses_abi.py check-imports BINARY abi/libramses19.symbols
    ramses_abi.py set-interp BINARY /lib/ld-linux-x86-64.so.2

dump-symbols writes the ramses:: exports of the library
(libramses-shared-lib-wayland-ivi-egl-es-3-0.so.19.0 or .so.27.0,
"name TYPE size"). stub-source turns such a list into C for a link-only
stub library (build it with -Wl,-soname,<the library's soname>).
check-imports fails if BINARY imports a ramses symbol the unit's library
does not export, or links a copy of a library object with another size.
set-interp rewrites a binary's program interpreter (the unit has no /lib64;
zig 0.16 rejects --dynamic-linker while building its C++ runtime).
Needs pyelftools.
"""
import sys

from elftools.elf.elffile import ELFFile


def is_ramses(name):
    # Public API only: ramses::, not ramses_internal:: or the bundled
    # CommonAPI/vsomeip/std template instantiations.
    return '6ramses' in name and '15ramses_internal' not in name


def soname_and_build_id(e):
    soname = build_id = '?'
    for tag in e.get_section_by_name('.dynamic').iter_tags():
        if tag.entry.d_tag == 'DT_SONAME':
            soname = tag.soname
    for sec in e.iter_sections():
        if sec['sh_type'] == 'SHT_NOTE':
            for note in sec.iter_notes():
                if note['n_type'] == 'NT_GNU_BUILD_ID':
                    build_id = note['n_desc']
    return soname, build_id


def dump_symbols(path):
    e = ELFFile(open(path, 'rb'))
    out = []
    for s in e.get_section_by_name('.dynsym').iter_symbols():
        if s['st_shndx'] != 'SHN_UNDEF' and s.name and is_ramses(s.name):
            kind = s['st_info']['type'].replace('STT_', '')
            if kind in ('FUNC', 'OBJECT'):
                out.append((s.name, kind, s['st_size']))
    soname, build_id = soname_and_build_id(e)
    print('# SPDX-License-Identifier: MPL-2.0')
    print('# Copyright (C) 2026 Robert Nisipeanu')
    print('# Exported ramses:: symbols of the head unit\'s /usr/lib/%s' % soname)
    print('# (BuildID %s): RAMSES (https://github.com/bmwcarit/ramses),' % build_id)
    print('# BMW Car IT GmbH, MPL-2.0.')
    print('# Regenerate: tools/ramses_abi.py dump-symbols <lib>')
    for name, kind, size in sorted(set(out)):
        print('%s %s %d' % (name, kind, size))


def load_symbols(path):
    syms = {}
    for line in open(path):
        line = line.split('#', 1)[0].strip()
        if line:
            name, kind, size = line.split()
            syms[name] = (kind, int(size))
    return syms


def stub_source(path):
    print('/* Link-only stub for the library %s lists. Generated by tools/ramses_abi.py. */' % path)
    for name, (kind, size) in sorted(load_symbols(path).items()):
        if kind == 'FUNC':
            print('void %s(void) {}' % name)
        else:
            print('const unsigned char %s[%d] = {0};' % (name, max(size, 1)))


def check_imports(binary, symbols_path):
    exported = load_symbols(symbols_path)
    e = ELFFile(open(binary, 'rb'))
    dynsym = list(e.get_section_by_name('.dynsym').iter_symbols())
    problems = []
    imports = sorted(s.name for s in dynsym if s['st_shndx'] == 'SHN_UNDEF' and s.name and is_ramses(s.name))
    for name in imports:
        if name not in exported:
            problems.append('imports %s, which the unit\'s libramses does not export' % name)
    for s in dynsym:
        if s['st_shndx'] != 'SHN_UNDEF' and s.name in exported and s['st_size'] != exported[s.name][1]:
            problems.append('copy of %s has size %d, library has %d' % (s.name, s['st_size'], exported[s.name][1]))
    for p in problems:
        print('FAIL  ' + p)
    if problems:
        return 1
    print('OK    %s: %d ramses imports, all exported by the unit\'s libramses' % (binary, len(imports)))
    return 0


def set_interp(binary, interp):
    # Rewrites PT_INTERP in place; the new path must fit in the existing one.
    with open(binary, 'r+b') as f:
        e = ELFFile(f)
        seg = [s for s in e.iter_segments() if s['p_type'] == 'PT_INTERP']
        if len(seg) != 1:
            print('FAIL  %s has no PT_INTERP' % binary)
            return 1
        offset, size = seg[0]['p_offset'], seg[0]['p_filesz']
        new = interp.encode() + b'\0'
        if len(new) > size:
            print('FAIL  %s does not fit in PT_INTERP (%d bytes)' % (interp, size))
            return 1
        f.seek(offset)
        f.write(new.ljust(size, b'\0'))
    print('OK    %s: interpreter %s' % (binary, interp))
    return 0


def main(argv):
    if len(argv) == 4 and argv[1] == 'set-interp':
        return set_interp(argv[2], argv[3])
    if len(argv) == 3 and argv[1] == 'dump-symbols':
        dump_symbols(argv[2])
        return 0
    if len(argv) == 3 and argv[1] == 'stub-source':
        stub_source(argv[2])
        return 0
    if len(argv) == 4 and argv[1] == 'check-imports':
        return check_imports(argv[2], argv[3])
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
