"""Import check for the unit's libmfx (Intel Media SDK), libva and IAS AVB
bridge. The stubs are generated by the cluster renderer's ramses_abi.py (which
handles FUNC and OBJECT symbols); this checks the built binary's imports
against the real exports, which that tool filters to ramses only.

    woc_abi.py check-imports BINARY --prefix P [P...] -- SYMBOLS...
        fail if BINARY imports a symbol starting with any prefix P that the
        given .symbols lists (the unit libraries' exports) do not provide

A .symbols line is "name", or "name TYPE size" (TYPE/size ignored here). A
versioned name "MFXInit@@LIBMFX_1.0" is compared on its bare name, because an
undefined import records the bare name plus a separate version.
Needs pyelftools.
"""
import sys


def bare(name):
    return name.split('@', 1)[0]


def load_symbols(paths):
    names = set()
    for path in paths:
        for line in open(path):
            line = line.split('#', 1)[0].strip()
            if line:
                names.add(bare(line.split()[0]))
    return names


def check_imports(binary, prefixes, symbol_paths):
    from elftools.elf.elffile import ELFFile
    exported = load_symbols(symbol_paths)
    e = ELFFile(open(binary, 'rb'))
    dynsym = list(e.get_section_by_name('.dynsym').iter_symbols())
    imports = sorted({bare(s.name) for s in dynsym
                      if s['st_shndx'] == 'SHN_UNDEF' and s.name
                      and any(bare(s.name).startswith(p) for p in prefixes)})
    problems = [name for name in imports if name not in exported]
    for name in problems:
        print('FAIL  imports %s, which the unit\'s libraries do not export' % name)
    if problems:
        return 1
    print('OK    %s: %d checked imports, all exported by the unit\'s libraries' % (binary, len(imports)))
    return 0


def main(argv):
    if len(argv) >= 5 and argv[1] == 'check-imports' and argv[3] == '--prefix' and '--' in argv:
        sep = argv.index('--')
        return check_imports(argv[2], argv[4:sep], argv[sep + 1:])
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
